package com.company.feedback.common;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * 统一响应状态码枚举
 *
 * <p>设计说明：
 * <ul>
 *   <li>200 表示业务成功</li>
 *   <li>4xx 表示客户端问题（参数错误、未登录、无权限、资源不存在）</li>
 *   <li>409 表示状态冲突（非法状态跳转、乐观锁并发冲突）</li>
 *   <li>503 是本项目特意设计的：<b>AI 服务不可用</b>，
 *       它不代表业务失败，业务流程应继续由人工完成</li>
 * </ul>
 *
 * @author 反馈改进助手项目组
 */
@Getter
@AllArgsConstructor
public enum ResultCode {

    /* ==================== 成功 ==================== */
    /** 操作成功 */
    SUCCESS(200, "操作成功"),

    /* ==================== 客户端错误 (4xx) ==================== */
    /** 请求参数错误 */
    BAD_REQUEST(400, "请求参数错误"),
    /** 未登录或 Token 已失效 */
    UNAUTHORIZED(401, "未登录或登录已失效，请重新登录"),
    /** 无权限执行该操作 */
    FORBIDDEN(403, "无权限执行此操作"),
    /** 资源不存在 */
    NOT_FOUND(404, "记录不存在或已被删除"),

    /**
     * 状态冲突
     *
     * <p>用于两类场景：
     * <ol>
     *   <li>非法的状态跳转（如 待开发 → 已完成）</li>
     *   <li>乐观锁并发冲突（他人已修改同一记录）</li>
     * </ol>
     */
    CONFLICT(409, "数据状态冲突"),

    /* ==================== 服务端错误 (5xx) ==================== */
    /** 服务器内部错误 */
    INTERNAL_ERROR(500, "服务器内部错误，请稍后重试"),

    /**
     * AI 服务不可用（降级码）
     *
     * <p>出现此码时，前端应展示"已切换为手工模式"提示，
     * 并提供手工创建入口，保证业务流程不中断。
     */
    AI_UNAVAILABLE(503, "AI 服务暂不可用，已切换为手工模式"),

    /** AI 返回内容无法解析 */
    AI_BAD_RESPONSE(502, "AI 返回内容格式异常，请重试或改用手工模式");

    /** 状态码 */
    private final int code;

    /** 默认提示信息 */
    private final String message;
}
